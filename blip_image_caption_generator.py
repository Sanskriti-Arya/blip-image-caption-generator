# 12. Generate Image Caption Function
def generate_caption(
    image,
    max_tokens=40,
    beams=5
):
    """
    Generate a caption for an input image using the BLIP model.

    Parameters:
        image (PIL.Image): Input image.
        max_tokens (int): Maximum number of generated tokens.
        beams (int): Number of beams for beam search.

    Returns:
        str: Generated image caption.
    """

    inputs = processor(
        image,
        return_tensors="pt"
    ).to(device)

    with torch.no_grad():

        output = model.generate(
            **inputs,
            max_new_tokens=max_tokens,
            num_beams=beams,
            early_stopping=True
        )

    caption = processor.decode(
        output[0],
        skip_special_tokens=True
    )

    return caption

