# 21. import gradio
import gradio as gr

def caption_app(image, beams, tokens):

    return generate_caption(
        image,
        beams=int(beams),
        max_tokens=int(tokens)
    )

demo = gr.Interface(

    fn=caption_app,

    inputs=[
        gr.Image(type="pil"),
        gr.Slider(1, 10, step=1, value=5, label="Beam Search"),
        gr.Slider(10, 100, step=1, value=40, label="Max Tokens")
    ],   # <-- Comma here

    outputs="text",

    title="AI Image Caption Generator",

    description="Upload an image to generate a caption."

)

demo.launch()

